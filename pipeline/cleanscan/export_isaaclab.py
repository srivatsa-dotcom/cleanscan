"""Writes ``export/isaaclab_scene.py``: an example Isaac Lab scene config for the USD.

Not tested here (Isaac Lab is not installable in CI); the USD itself is checked with pxr.
"""

from __future__ import annotations

from pathlib import Path

from .export_usd import _safe

TEMPLATE = '''"""Isaac Lab scene for the CleanScan scan "{name}" (generated, edit freely).

Usage inside an Isaac Lab task:

    from isaaclab_scene import CleanScanSceneCfg
    scene = CleanScanSceneCfg(num_envs=16, env_spacing=8.0)

The whole scan is one USD; pickable objects and articulated objects inside it are exposed as
RigidObject / Articulation assets (``spawn=None`` = the prim already exists in the USD).
NOTE: generated by CleanScan but not tested against an Isaac Lab installation.
"""

import os

import isaaclab.sim as sim_utils
from isaaclab.actuators import ImplicitActuatorCfg
from isaaclab.assets import ArticulationCfg, AssetBaseCfg, RigidObjectCfg
from isaaclab.scene import InteractiveSceneCfg
from isaaclab.utils import configclass

USD_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "scene.usda")
ROOT = "{{ENV_REGEX_NS}}/Scan"


@configclass
class CleanScanSceneCfg(InteractiveSceneCfg):
    scan = AssetBaseCfg(prim_path=ROOT, spawn=sim_utils.UsdFileCfg(usd_path=USD_PATH))
    light = AssetBaseCfg(prim_path="/World/light",
                         spawn=sim_utils.DomeLightCfg(intensity=2000.0, color=(0.9, 0.9, 0.9)))
{assets}
'''

RIGID = '''    {var} = RigidObjectCfg(prim_path=ROOT + "/World/{prim}", spawn=None,
                           init_state=RigidObjectCfg.InitialStateCfg(pos={pos}, rot={rot}))
'''

ARTIC = '''    {var} = ArticulationCfg(
        prim_path=ROOT + "/World/{prim}", spawn=None,
        init_state=ArticulationCfg.InitialStateCfg(pos={pos}, rot={rot}),
        actuators={{"passive": ImplicitActuatorCfg(joint_names_expr=[".*"], stiffness=0.0, damping={damping})}},
    )
'''


def write_example(scene, scene_dir: Path) -> Path:
    from scipy.spatial.transform import Rotation

    assets = []
    for o in scene.objects:
        prim = _safe(o.id)
        var = prim.lower()
        pos = tuple(round(float(v), 5) for v in o.pose[:3, 3])
        x, y, z, w = Rotation.from_matrix(o.pose[:3, :3]).as_quat()
        rot = tuple(round(float(v), 6) for v in (w, x, y, z))
        if o.type == "pickable":
            assets.append(RIGID.format(var=var, prim=prim, pos=pos, rot=rot))
        elif o.type == "articulated":
            damping = max((j.damping for j in o.joints), default=0.5)
            assets.append(ARTIC.format(var=var, prim=prim, pos=pos, rot=rot, damping=damping))
    out = Path(scene_dir) / "export" / "isaaclab_scene.py"
    out.write_text(TEMPLATE.format(name=scene.name, assets="".join(assets) or "    pass\n"))
    return out
